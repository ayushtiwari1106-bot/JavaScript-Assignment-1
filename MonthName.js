// 21. Month Name 
// Take a number from 1 to 12. 
// Use switch-case to display the corresponding month. 
// Example: 
// 1  → January 
// 2  → February 
// 3  → March 
// ... 
// 12 → December 
// For an invalid number: 
// Invalid month 

let month = 9;

switch (month) {
    case 1:
        console.log("january")
        break;
    case 2:
        console.log("febuary")
        break;
    case 3:
        console.log("march")
        break;
    case 4:
        console.log("april")
        break;
    case 5:
        console.log("may")
        break;
    case 6:
        console.log("june")
        break;
    case 7:
        console.log("july")
        break;
      case 8:
        console.log("August")
        break;
    case 9:
        console.log("September")
        break;
    case 10:
        console.log("October")
        break;
    case 11:
        console.log("November")
        break;
    case 12:
        console.log("December")
        break;    
    default:
        console.log("invailid")
} 
